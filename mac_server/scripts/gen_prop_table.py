#!/usr/bin/env python3
"""Generate Source/SimWorld/Private/SWPropTable.inl, the placeholder size table for ASWProp.

Buildings and trees take their footprint from simworld's data/bounding_boxes.json (cm, the
same numbers the city generator uses to lay buildings out, so placeholders never overlap).
Street elements in that file all carry a dummy 256 cm cube, so their sizes are hand-picked
real-world guesses below.

    python3 scripts/gen_prop_table.py [path/to/bounding_boxes.json]

Re-run after editing ELEMENTS; the .inl is checked in so the build needs no Python.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_BOXES = os.path.expanduser('~/Desktop/kokopelli/simworld/data/bounding_boxes.json')
OUT = os.path.join(ROOT, 'Source', 'SimWorld', 'Private', 'SWPropTable.inl')

# key (asset name without _C): (shape, category, x, y, z, is_seat)
# Categories follow ue_assets.json colour groups. Sizes in cm.
ELEMENTS = {
    'BP_Box':          ('Box',      'Box',             60, 40, 40, False),
    'BP_Box2':         ('Box',      'Box',             50, 50, 50, False),
    'BP_Box3':         ('Box',      'Box',             40, 30, 30, False),
    'BP_Can':          ('Cylinder', 'Can',             8, 8, 12, False),
    'BP_Can2':         ('Cylinder', 'Can',             8, 8, 12, False),
    'BP_Soda1':        ('Cylinder', 'Can',             7, 7, 12, False),
    'BP_Soda2':        ('Cylinder', 'Can',             7, 7, 12, False),
    'BP_Soda3':        ('Cylinder', 'Can',             7, 7, 20, False),
    'BP_Soda4':        ('Cylinder', 'Can',             7, 7, 20, False),
    'BP_Cart':         ('Box',      'Furniture',       150, 80, 110, False),
    'BP_Cart2':        ('Box',      'Furniture',       150, 80, 110, False),
    'BP_Couch':        ('Box',      'Furniture',       200, 90, 85, True),
    'Couch':           ('Box',      'Furniture',       200, 90, 85, True),
    'BP_Hydrant':      ('Cylinder', 'StreetFurniture', 35, 35, 80, False),
    'BP_RoadCone':     ('Cone',     'StreetFurniture', 35, 35, 70, False),
    'RoadCone':        ('Cone',     'StreetFurniture', 35, 35, 70, False),
    'BP_RoadBlocker':  ('Box',      'RoadBlocker',     200, 40, 100, False),
    'RoadBlocker':     ('Box',      'RoadBlocker',     200, 40, 100, False),
    'BP_Rabbish':      ('Sphere',   'Trash',           70, 60, 50, False),
    'BP_Trash_bin_a':  ('Cylinder', 'Trash',           60, 60, 100, False),
    'BP_Trash_bin_b':  ('Cylinder', 'Trash',           60, 60, 100, False),
    'BP_Trash_can':    ('Cylinder', 'Trash',           50, 50, 90, False),
    'BP_Table':        ('Box',      'Table',           120, 80, 75, False),
    'BP_Table2':       ('Cylinder', 'Table',           90, 90, 75, False),
    'BP_Table3':       ('Box',      'Table',           160, 90, 75, False),
    'Table':           ('Box',      'Table',           120, 80, 75, False),
    'BP_Scooter_01':   ('Box',      'Scooter',         120, 50, 110, False),
    'BP_Scooter_02':   ('Box',      'Scooter',         120, 50, 110, False),
    'BP_Scooter_03':   ('Box',      'Scooter',         120, 50, 110, False),
    'BP_Scooter_04':   ('Box',      'Scooter',         120, 50, 110, False),
}


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_BOXES
    with open(path) as f:
        boxes = json.load(f)

    rows = []
    buildings = boxes['buildings']
    sizes = sorted(v['bbox']['x'] * v['bbox']['y'] for v in buildings.values())
    median = next(v['bbox'] for v in buildings.values() if v['bbox']['x'] * v['bbox']['y'] == sizes[len(sizes) // 2])
    for i in range(1, 127):
        key = f'BP_Building_{i:02d}'
        bbox = buildings.get(key + '_C', {}).get('bbox')
        note = ''
        if bbox is None:
            bbox = median  # 57 and 120 have no entry; ship them anyway (SPEC 4.1)
            note = '  // not in bounding_boxes.json: median footprint'
        rows.append((key, 'Building', 'Box', 'Building', bbox['x'], bbox['y'], bbox['z'], False, note))

    for name, v in boxes['elements'].items():
        if name.startswith('BP_Tree'):
            b = v['bbox']
            rows.append((name[:-2], 'Tree', 'Box', 'Vegetation', b['x'], b['y'], b['z'], False, ''))

    for key, (shape, cat, x, y, z, seat) in ELEMENTS.items():
        rows.append((key, 'Small', shape, cat, x, y, z, seat, ''))

    lines = [
        '// GENERATED by scripts/gen_prop_table.py from simworld data/bounding_boxes.json. Do not edit by hand.',
        '// { Key, Kind, Shape, Category, SizeX, SizeY, SizeZ (cm), bSeat }',
    ]
    for key, kind, shape, cat, x, y, z, seat, note in rows:
        lines.append(f'{{ TEXT("{key}"), ESWPropKind::{kind}, ESWShape::{shape}, ESWPropCategory::{cat}, '
                     f'{x:.1f}f, {y:.1f}f, {z:.1f}f, {"true" if seat else "false"} }},{note}')
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {len(rows)} entries to {OUT}')


if __name__ == '__main__':
    main()
